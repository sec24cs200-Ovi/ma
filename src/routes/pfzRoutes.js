// Aliases
PFZ_ZONES_DATA.vizag = PFZ_ZONES_DATA.visakhapatnam;
PFZ_ZONES_DATA.thoothukudi = PFZ_ZONES_DATA.tuticorin;
PFZ_ZONES_DATA.kasimedu = PFZ_ZONES_DATA.chennai;

function normalizeRegion(raw) {
  if (!raw) return 'rameswaram';
  const clean = String(raw).toLowerCase().trim().replace(/[^a-z]/g, '');
  if (clean.includes('kanya')) return 'kanyakumari';
  if (clean.includes('chennai') || clean.includes('kasimedu')) return 'chennai';
  if (clean.includes('tuticorin') || clean.includes('thoothu')) return 'tuticorin';
  if (clean.includes('kochi') || clean.includes('cochin')) return 'kochi';
  if (clean.includes('vizag') || clean.includes('visakha')) return 'visakhapatnam';
  if (clean.includes('veraval')) return 'veraval';
  if (clean.includes('paradip') || clean.includes('paradeep')) return 'paradip';
  if (clean.includes('rames')) return 'rameswaram';
  return clean;
}

/**
 * GET /api/pfz/zones
 * Returns potential fishing zones by region
 */
router.get('/zones', (req, res) => {
  const normalized = normalizeRegion(req.query.region);
  const zones = PFZ_ZONES_DATA[normalized] || PFZ_ZONES_DATA[req.query.region] || PFZ_ZONES_DATA.rameswaram;

  res.json({
    success: true,
    region: normalized,
    requestedRegion: req.query.region || 'rameswaram',
    total: zones.length,
    zones,
    source: 'ISRO OceanSat-3 OCM-3 & INCOIS Marine Fishery Advisory'
  });
});

module.exports = router;
